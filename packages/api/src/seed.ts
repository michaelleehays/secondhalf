import type { GameState } from "@second-half/contracts";

export interface SeedUser {
  id: string;
  email: string;
  /** Local development only. */
  password: string;
}

/** The local test player. Never used outside a local database. */
export const SEED_USER: SeedUser = {
  id: "00000000-0000-4000-8000-000000000042",
  email: "sample@second-half.local",
  password: "sample-password",
};

const lit = (s: string) => `'${s.replace(/'/g, "''")}'`;

/**
 * SQL that creates a local auth user who can sign in with email and password,
 * then saves `state` for them through save_step_result.
 */
export function seedSql(state: GameState, user: SeedUser = SEED_USER): string {
  const json = JSON.stringify({ ...state, userId: user.id }, null, 2);
  return `-- Generated by \`npm run seed:generate -w @second-half/api\` from SAMPLE_STATE. Do not edit by hand.
-- Local development only: creates the test player ${user.email} (password: ${user.password}).
-- One transaction, safe to rerun: the user is created once and the save is an upsert.

begin;

insert into auth.users (
  instance_id, id, aud, role, email, encrypted_password, email_confirmed_at,
  raw_app_meta_data, raw_user_meta_data, created_at, updated_at,
  confirmation_token, email_change, email_change_token_new, recovery_token
) values (
  '00000000-0000-0000-0000-000000000000', ${lit(user.id)}, 'authenticated', 'authenticated', ${lit(user.email)},
  extensions.crypt(${lit(user.password)}, extensions.gen_salt('bf')), now(),
  '{"provider":"email","providers":["email"]}', '{}', now(), now(), '', '', '', ''
) on conflict (id) do nothing;

insert into auth.identities (id, user_id, provider_id, identity_data, provider, last_sign_in_at, created_at, updated_at)
values (
  gen_random_uuid(), ${lit(user.id)}, ${lit(user.id)},
  jsonb_build_object('sub', ${lit(user.id)}, 'email', ${lit(user.email)}, 'email_verified', true),
  'email', now(), now(), now()
) on conflict (provider_id, provider) do nothing;

-- Save as the server would (service role), through the same function the client uses.
select set_config('request.jwt.claims', '{"role":"service_role"}', true);
select public.save_step_result(${lit(user.id)}, ${lit(json)}::jsonb, '[]'::jsonb, '[]'::jsonb);

commit;
`;
}
